/**
 * ChildProvisioningScreen (v3.6.0 Design Overhaul)
 * Provides the parent-authorized provisioning flow for child devices.
 * Requires a 6-digit cryptographic pairing code generated by the parent (15-min TTL).
 * Upon successful claim, binds the child device to the family Room DB and locks the device into Child Mode.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ChildProvisioningScreen(
    viewModel: SafeBandViewModel,
    onNavigateBack: () -> Unit,
    onProvisioningComplete: () -> Unit,
    modifier: Modifier = Modifier
) {
    var pairingCode by remember { mutableStateOf("") }
    var childName by remember { mutableStateOf("") }
    var isVerifying by remember { mutableStateOf(false) }
    var errorMessage by remember { mutableStateOf<String?>(null) }
    var successDeviceName by remember { mutableStateOf<String?>(null) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text = "Device Pairing",
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = "Back"
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.background
                )
            )
        },
        modifier = modifier
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(MaterialTheme.colorScheme.background)
                .padding(innerPadding)
                .padding(horizontal = SafeBandSpacing.lg)
                .verticalScroll(rememberScrollState()),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Spacer(modifier = Modifier.height(SafeBandSpacing.sm))

            Surface(
                shape = CircleShape,
                color = SafeBandColor.PrimaryBrand.copy(alpha = 0.12f),
                border = BorderStroke(1.5.dp, SafeBandColor.PrimaryBrand.copy(alpha = 0.35f)),
                modifier = Modifier.size(72.dp)
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Icon(
                        imageVector = Icons.Default.QrCodeScanner,
                        contentDescription = null,
                        tint = SafeBandColor.PrimaryBrand,
                        modifier = Modifier.size(34.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(SafeBandSpacing.md))

            Text(
                text = "Pair with Guardian",
                style = MaterialTheme.typography.displayMedium,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onBackground
            )

            Text(
                text = "Enter the 6-digit one-time code shown on your parent's phone under 'Add / Pair Child'.",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
                modifier = Modifier.padding(top = 4.dp, start = 8.dp, end = 8.dp)
            )

            Spacer(modifier = Modifier.height(SafeBandSpacing.xxl))

            SafeBandCard(
                modifier = Modifier.fillMaxWidth(),
                shape = SafeBandShapes.ExtraLarge,
                elevation = 2.dp
            ) {
                Column(modifier = Modifier.padding(SafeBandSpacing.lg)) {
                    Text(
                        text = "Child Information",
                        style = MaterialTheme.typography.titleSmall,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )

                    Spacer(modifier = Modifier.height(SafeBandSpacing.sm))

                    SafeBandTextField(
                        value = childName,
                        onValueChange = { childName = it },
                        label = "Child's Name",
                        placeholder = "e.g. Leo",
                        singleLine = true,
                        modifier = Modifier.testTag("child_name_input")
                    )

                    Spacer(modifier = Modifier.height(SafeBandSpacing.lg))

                    Text(
                        text = "6-Digit Pairing Code",
                        style = MaterialTheme.typography.titleSmall,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )

                    Spacer(modifier = Modifier.height(SafeBandSpacing.sm))

                    OutlinedTextField(
                        value = pairingCode,
                        onValueChange = { input ->
                            val filtered = input.filter { it.isDigit() }.take(6)
                            pairingCode = filtered
                        },
                        label = { Text("Pairing Code") },
                        placeholder = { Text("123456") },
                        singleLine = true,
                        shape = SafeBandShapes.Medium,
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                        textStyle = MaterialTheme.typography.headlineMedium.copy(
                            letterSpacing = 8.sp,
                            textAlign = TextAlign.Center
                        ),
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("pairing_code_input")
                    )

                    Spacer(modifier = Modifier.height(SafeBandSpacing.md))

                    errorMessage?.let { err ->
                        SafeBandCard(
                            modifier = Modifier.fillMaxWidth(),
                            containerColor = SafeBandColor.EmergencySurfaceLight,
                            borderColor = SafeBandColor.EmergencyBorder
                        ) {
                            Text(
                                text = err,
                                style = MaterialTheme.typography.bodySmall,
                                color = SafeBandColor.EmergencyDark,
                                modifier = Modifier.padding(SafeBandSpacing.sm)
                            )
                        }
                        Spacer(modifier = Modifier.height(SafeBandSpacing.md))
                    }

                    successDeviceName?.let { name ->
                        SafeBandCard(
                            modifier = Modifier.fillMaxWidth(),
                            containerColor = SafeBandColor.SuccessSurfaceLight,
                            borderColor = SafeBandColor.SuccessBorder
                        ) {
                            Row(
                                modifier = Modifier.padding(SafeBandSpacing.sm),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Icon(
                                    imageVector = Icons.Default.CheckCircle,
                                    contentDescription = null,
                                    tint = SafeBandColor.SuccessDark,
                                    modifier = Modifier.size(20.dp)
                                )
                                Spacer(modifier = Modifier.width(8.dp))
                                Text(
                                    text = "Successfully paired with $name! Entering child mode...",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = SafeBandColor.SuccessDark
                                )
                            }
                        }
                        Spacer(modifier = Modifier.height(SafeBandSpacing.md))
                    }

                    SafeBandPrimaryButton(
                        text = if (isVerifying) "Verifying..." else "Authorize & Complete",
                        icon = Icons.Default.Watch,
                        isLoading = isVerifying,
                        enabled = pairingCode.length == 6 && childName.isNotBlank() && !isVerifying,
                        onClick = {
                            isVerifying = true
                            errorMessage = null
                            viewModel.claimChildPairingCode(
                                code = pairingCode,
                                childName = childName
                            ) { result ->
                                isVerifying = false
                                when (result) {
                                    is ProvisioningResult.Success -> {
                                        successDeviceName = result.pairedChild.childName
                                        onProvisioningComplete()
                                    }
                                    is ProvisioningResult.Expired -> {
                                        errorMessage = "This pairing code has expired (15-min TTL). Please generate a new code from Parent Mode."
                                    }
                                    is ProvisioningResult.InvalidCode -> {
                                        errorMessage = "Invalid pairing code. Please double-check the 6-digit code shown on the parent's phone."
                                    }
                                    is ProvisioningResult.Error -> {
                                        errorMessage = result.error.message ?: "An unexpected error occurred during pairing."
                                    }
                                }
                            }
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("submit_pairing_code_button")
                    )
                }
            }

            Spacer(modifier = Modifier.height(SafeBandSpacing.xxxl))
        }
    }
}
