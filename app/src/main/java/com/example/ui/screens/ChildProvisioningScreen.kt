/**
 * ChildProvisioningScreen (v3.3)
 * Provides the parent-authorized provisioning flow for child devices.
 * Requires a 6-digit cryptographic pairing code generated by the parent (15-min TTL).
 * Upon successful claim, binds the child device to the family Room DB and locks the device into Child Mode.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ChildProvisioningScreen(
    viewModel: SafeBandViewModel,
    onNavigateBack: () -> Unit,
    onProvisioningComplete: () -> Unit,
    modifier: Modifier = Modifier
) {
    var pairingCode by remember { mutableStateOf("") }
    var childName by remember { mutableStateOf("") }
    var isVerifying by remember { mutableStateOf(false) }
    var errorMessage by remember { mutableStateOf<String?>(null) }
    var successDeviceName by remember { mutableStateOf<String?>(null) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text = "CHILD PROVISIONING",
                        style = MaterialTheme.typography.titleSmall,
                        fontFamily = FontFamily.Monospace,
                        fontWeight = FontWeight.Bold,
                        color = PhosphorWhite,
                        letterSpacing = 1.sp
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = "Back",
                            tint = PhosphorWhite
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = CarbonChassis)
            )
        },
        modifier = modifier
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(CarbonChassis)
                .padding(innerPadding)
                .padding(20.dp)
                .verticalScroll(rememberScrollState()),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Spacer(modifier = Modifier.height(12.dp))

            Surface(
                shape = RoundedCornerShape(8.dp),
                color = GlassSurfaceLowest,
                modifier = Modifier
                    .size(64.dp)
                    .border(1.dp, PhosphorWhite, RoundedCornerShape(8.dp))
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Icon(
                        imageVector = Icons.Default.QrCodeScanner,
                        contentDescription = null,
                        tint = PhosphorWhite,
                        modifier = Modifier.size(32.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(14.dp))

            Text(
                text = "PAIR WITH GUARDIAN",
                style = MaterialTheme.typography.titleMedium,
                fontFamily = FontFamily.Monospace,
                fontWeight = FontWeight.Bold,
                color = PhosphorWhite,
                letterSpacing = 1.5.sp
            )

            Text(
                text = "Enter the 6-digit one-time code shown on your parent's phone under 'Add / Pair Child'.",
                style = MaterialTheme.typography.bodySmall,
                fontFamily = FontFamily.Monospace,
                color = MilledSilver,
                textAlign = TextAlign.Center,
                fontSize = 11.sp,
                modifier = Modifier.padding(top = 6.dp, start = 12.dp, end = 12.dp)
            )

            Spacer(modifier = Modifier.height(24.dp))

            GlassCard(
                modifier = Modifier.fillMaxWidth(),
                backgroundColor = GlassSurface,
                borderColor = GlassBorderStrong,
                padding = 18.dp
            ) {
                Text(
                    text = "CHILD INFORMATION",
                    style = MaterialTheme.typography.labelSmall,
                    fontFamily = FontFamily.Monospace,
                    fontWeight = FontWeight.Bold,
                    color = ObsidianOutline,
                    fontSize = 9.sp,
                    letterSpacing = 1.sp
                )

                Spacer(modifier = Modifier.height(10.dp))

                OutlinedTextField(
                    value = childName,
                    onValueChange = { childName = it },
                    label = { Text("Child's Name", fontFamily = FontFamily.Monospace) },
                    placeholder = { Text("e.g. Aarav", fontFamily = FontFamily.Monospace, color = ObsidianOutline) },
                    singleLine = true,
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = PhosphorWhite,
                        unfocusedBorderColor = GlassBorder,
                        focusedTextColor = PhosphorWhite,
                        unfocusedTextColor = PhosphorWhite
                    ),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("child_name_input")
                )

                Spacer(modifier = Modifier.height(16.dp))

                Text(
                    text = "6-DIGIT PAIRING CODE",
                    style = MaterialTheme.typography.labelSmall,
                    fontFamily = FontFamily.Monospace,
                    fontWeight = FontWeight.Bold,
                    color = ObsidianOutline,
                    fontSize = 9.sp,
                    letterSpacing = 1.sp
                )

                Spacer(modifier = Modifier.height(10.dp))

                OutlinedTextField(
                    value = pairingCode,
                    onValueChange = { input ->
                        val filtered = input.filter { it.isDigit() }.take(6)
                        pairingCode = filtered
                    },
                    label = { Text("Pairing Code (6 Digits)", fontFamily = FontFamily.Monospace) },
                    placeholder = { Text("123456", fontFamily = FontFamily.Monospace, color = ObsidianOutline) },
                    singleLine = true,
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                    textStyle = MaterialTheme.typography.titleLarge.copy(
                        fontFamily = FontFamily.Monospace,
                        letterSpacing = 6.sp,
                        textAlign = TextAlign.Center
                    ),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = PhosphorWhite,
                        unfocusedBorderColor = GlassBorder,
                        focusedTextColor = PhosphorWhite,
                        unfocusedTextColor = PhosphorWhite
                    ),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("pairing_code_input")
                )

                Spacer(modifier = Modifier.height(16.dp))

                errorMessage?.let { err ->
                    GlassCard(
                        modifier = Modifier.fillMaxWidth(),
                        backgroundColor = GlassHazard,
                        borderColor = Color(0xFFFF5252),
                        padding = 10.dp
                    ) {
                        Text(
                            text = err,
                            style = MaterialTheme.typography.bodySmall,
                            fontFamily = FontFamily.Monospace,
                            color = Color(0xFFFF5252),
                            fontSize = 10.sp
                        )
                    }
                    Spacer(modifier = Modifier.height(12.dp))
                }

                if (isVerifying) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.Center,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        CircularProgressIndicator(
                            color = PhosphorWhite,
                            modifier = Modifier.size(20.dp),
                            strokeWidth = 2.dp
                        )
                        Spacer(modifier = Modifier.width(10.dp))
                        Text(
                            text = "Verifying Challenge with Parent Node...",
                            style = MaterialTheme.typography.bodySmall,
                            fontFamily = FontFamily.Monospace,
                            color = MilledSilver
                        )
                    }
                    Spacer(modifier = Modifier.height(12.dp))
                }

                GlassButton(
                    text = "Verify & Pair Device",
                    icon = Icons.Default.Lock,
                    enabled = pairingCode.length == 6 && childName.isNotBlank() && !isVerifying,
                    onClick = {
                        isVerifying = true
                        errorMessage = null
                        viewModel.claimChildPairingCode(pairingCode, childName) { result ->
                            isVerifying = false
                            when (result) {
                                is ProvisioningResult.Success -> {
                                    successDeviceName = result.pairedChild.childName
                                    onProvisioningComplete()
                                }
                                is ProvisioningResult.Expired -> {
                                    errorMessage = "This 6-digit code has expired (15-min TTL). Please ask parent to generate a fresh code."
                                }
                                is ProvisioningResult.InvalidCode -> {
                                    errorMessage = "Invalid 6-digit pairing code. Please double-check the code on parent device."
                                }
                                is ProvisioningResult.Error -> {
                                    errorMessage = result.error.localizedMessage ?: "Pairing challenge could not be verified."
                                }
                            }
                        }
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("verify_pairing_code_button")
                )
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Lockdown Notice Card
            GlassCard(
                modifier = Modifier.fillMaxWidth(),
                backgroundColor = GlassSurfaceLowest,
                borderColor = ObsidianEtchedBorder,
                padding = 12.dp
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Default.Watch,
                        contentDescription = null,
                        tint = PhosphorWhite,
                        modifier = Modifier.size(20.dp)
                    )
                    Spacer(modifier = Modifier.width(10.dp))
                    Text(
                        text = "Once paired, this device will be locked into Child Mode. Returning to Parent settings will require guardian authorization.",
                        style = MaterialTheme.typography.bodySmall,
                        fontFamily = FontFamily.Monospace,
                        color = MilledSilver,
                        fontSize = 9.sp
                    )
                }
            }
        }
    }
}
